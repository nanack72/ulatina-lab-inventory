BEGIN;
SET LOCAL ROLE pes_owner;
CREATE TABLE public.foto_equipo (
  id_foto integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_equipo integer NOT NULL REFERENCES public.equipo(id_equipo) ON DELETE CASCADE,
  id_usuario integer NOT NULL REFERENCES public.usuario(id_usuario),
  nombre_archivo varchar(180) NOT NULL,
  mime varchar(30) NOT NULL CHECK(mime IN ('image/jpeg','image/png','image/webp')),
  datos bytea NOT NULL CHECK(octet_length(datos) BETWEEN 1 AND 5242880),
  fecha_creacion timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX foto_equipo_equipo_idx ON public.foto_equipo(id_equipo);
GRANT SELECT, INSERT, DELETE ON public.foto_equipo TO pes_runtime;
GRANT USAGE ON SEQUENCE public.foto_equipo_id_foto_seq TO pes_runtime;
COMMIT;
