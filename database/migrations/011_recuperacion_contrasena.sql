BEGIN;

SET LOCAL ROLE pes_owner;

CREATE TABLE IF NOT EXISTS public.recuperacion_contrasena (
  id_recuperacion integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario integer NOT NULL REFERENCES public.usuario(id_usuario) ON DELETE CASCADE,
  token_hash varchar(64) NOT NULL UNIQUE,
  expira_en timestamptz NOT NULL,
  usado_en timestamptz,
  creado_en timestamptz NOT NULL DEFAULT NOW(),
  CONSTRAINT recuperacion_contrasena_hash_hex CHECK (token_hash ~ '^[0-9a-f]{64}$')
);

CREATE INDEX IF NOT EXISTS recuperacion_contrasena_usuario_idx
  ON public.recuperacion_contrasena (id_usuario);

CREATE INDEX IF NOT EXISTS recuperacion_contrasena_expira_idx
  ON public.recuperacion_contrasena (expira_en);

CREATE OR REPLACE FUNCTION public.limpiar_tokens_recuperacion()
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  cantidad integer;
BEGIN
  DELETE FROM public.recuperacion_contrasena
  WHERE expira_en < NOW() - INTERVAL '1 day'
     OR (usado_en IS NOT NULL AND usado_en < NOW() - INTERVAL '1 day');
  GET DIAGNOSTICS cantidad = ROW_COUNT;
  RETURN cantidad;
END;
$$;

REVOKE ALL ON FUNCTION public.limpiar_tokens_recuperacion() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.limpiar_tokens_recuperacion() TO pes_runtime;

GRANT SELECT, INSERT ON TABLE public.recuperacion_contrasena TO pes_runtime;
GRANT UPDATE (usado_en) ON TABLE public.recuperacion_contrasena TO pes_runtime;
GRANT USAGE, SELECT ON SEQUENCE public.recuperacion_contrasena_id_recuperacion_seq TO pes_runtime;
GRANT UPDATE (contrasena_hash) ON TABLE public.usuario TO pes_runtime;

COMMIT;
